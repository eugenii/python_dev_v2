# Обоснование алгоритма
# Для расшифровки сжатых инструкций используется алгоритм на основе структуры данных «Сек» (Stack).
# Мы посимвольно просматриваем строку слева направо.Числа коэффициентов повторения собираются арифметически «на лету».
# Когда встречается открывающая скобка [, мы «замораживаем» текущее состояние (накопленную строку и число) и 
# сохраняем его в стек в виде кортежа. Это позволяет корректно обрабатывать любую глубину вложенности команд.
# Когда встречается закрывающая скобка ], мы извлекаем из стека сохранённый контекст верхнего уровня, умножаем 
# текущую подстроку на коэффициент и склеиваем результат с родительской строкой.
# Временная сложность (Time Complexity)
# Если N — длина исходной (сжатой) строки, а M — длина итоговой (развёрнутой) строки.Мы проходим по исходной строке один раз — 
# это занимает O(N) операций. Однако на этапе раскрытия скобок (символ ]) происходит копирование и склеивание строк. 
# В худшем случае (например, при сильном раскрытии строки вида 300[300[a]]) время будет пропорционально длине генерируемой строки.
# Благодаря тому, что мы не делаем промежуточных склеиваний в цикле для каждого символа, а эффективно раскрываем блоки через стек,
#  суммарное время работы алгоритма составляет O(N + M), где M — длина результирующей строки. 
# Так как по условию задачи лимиты на числа ограничены (до 300), время линейно зависит от размера выходных данных.
# Пространственная сложность (Space Complexity)
# Память под стек: в худшем случае стек кортежей может разрастись до O(N) при максимальной вложенности скобок 
# (например, 1[1[1[1[a]]]]). Память под результат: переменная current_str в процессе работы и финальная строка на выходе 
# занимают в памяти место, пропорциональное длине расшифрованного сообщения — O(M).
# Итоговая пространственная сложность: O(N + M). Мы тратим память на хранение стека символов и формирование результирующей строки.

import sys


def decode_instructions(compressed_str: str) -> str:
    """Расшифровывает сжатую строку инструкций марсохода."""
    stack: list[tuple[str, int]] = []
    current_str: str = ""
    current_num: int = 0

    for char in compressed_str:
        if char.isdigit():
            # Собираем число посимвольно.
            current_num = current_num * 10 + int(char)
        elif char == '[':
            # Сохраняем накопленную строку и число в стек, чтобы заняться вложенной частью.
            stack.append((current_str, current_num))
            # Сбрасываем текущие рабочие переменные
            current_str = ""
            current_num = 0
        elif char == ']':
            # Достаем из стека родительскую строку и коэффициент умножения
            prev_str, num = stack.pop()
            # Раскрываем текущие скобки и приклеиваем к родительской строке
            current_str = prev_str + current_str * num
        else:
            # Если это просто буква — добавляем к текущей строке
            current_str += char

    return current_str


if __name__ == "__main__":
    # Считываем строку, очищая от лишних пробелов и переносов
    input_data: str = sys.stdin.read().strip()
    print(decode_instructions(input_data))